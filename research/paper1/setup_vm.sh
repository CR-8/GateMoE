#!/usr/bin/env bash
# Prepare the 8 GB Google Cloud VM for the paper-1 campaign and start it. Safe to re-run.
#
#   curl -fsSL https://raw.githubusercontent.com/CR-8/GateMoE/paper1-cloud-experiment/research/paper1/setup_vm.sh | sudo bash
#
# What it does:
#   1. installs / updates GateMoE from this branch with Hindi + Kannada knowledge and voices
#      (scripts/install_cloud.sh; ~30-45 min on a fresh VM, minutes on an installed one)
#   2. adds the analysis packages (matplotlib, scipy, pypdf)
#   3. stops the GateMoE web service for the week (it must not load models during measurements)
#   4. writes the experiment config  /opt/gatemoe/data/paper1.yaml  (router memo cache off)
#   5. installs the `paper1` helper (status / log / bundle / stop / start)
#   6. installs + starts the systemd service gatemoe-paper1 (resumes by itself after a reboot)
#
# Options (environment, e.g. `... | sudo DAYS=6 bash`):
#   DAYS=7            campaign length (the deadline is fixed at the first start)
#   LANGS="hi kn"     extra lesson languages
#   SKIP_INSTALL=1    do not run install_cloud.sh (GateMoE already installed from this branch)
#   NO_START=1        set everything up but do not start the campaign
set -euo pipefail
REF="${GATEMOE_REF:-paper1-cloud-experiment}"
LANGS="${LANGS:-hi kn}"
DAYS="${DAYS:-7}"
HOME_DIR=/opt/gatemoe
DATA="$HOME_DIR/data"
SRC="$HOME_DIR/GateMoE"
VENV="$HOME_DIR/venv"
log() { printf '\n\033[1;34m== %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!! %s\033[0m\n' "$*" >&2; }
[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }
export HOME="${HOME:-/root}"

MEM_GB=$(awk '/MemTotal/ {printf "%.1f", $2/1048576}' /proc/meminfo)
echo "machine: $(uname -m), $(nproc) vCPU, ${MEM_GB} GB RAM, $(df -BG --output=avail / | tail -1 | tr -dc 0-9) GB free on /"

if [ "${SKIP_INSTALL:-0}" != 1 ]; then
  log "GateMoE ($REF) with languages: en $LANGS"
  curl -fsSL "https://raw.githubusercontent.com/CR-8/GateMoE/$REF/scripts/install_cloud.sh" \
    | GATEMOE_REF="$REF" LANGS="$LANGS" bash
fi
[ -x "$VENV/bin/gatemoe" ] || { echo "GateMoE is not installed under $HOME_DIR"; exit 1; }

log "Analysis packages"
"$VENV/bin/pip" install -q matplotlib scipy pypdf
command -v fincore >/dev/null || apt-get install -y -q util-linux >/dev/null || true

log "Stopping the web service for the campaign (re-enable later: sudo systemctl enable --now gatemoe)"
systemctl disable --now gatemoe 2>/dev/null || true

log "Experiment config $DATA/paper1.yaml"
"$VENV/bin/python" - "$DATA" <<'EOF'
import sys, yaml, pathlib
data = pathlib.Path(sys.argv[1])
base = yaml.safe_load((data / "gatemoe.yaml").read_text()) or {}
def merge(a, b):
    for k, v in b.items():
        a[k] = merge(a.get(k, {}), v) if isinstance(v, dict) and isinstance(a.get(k), dict) else v
    return a
conf = merge(base, {
    "router": {"memo_cache": False},          # every CLEF decision is paid for, as on a fresh request
    "llama": {"ready_timeout_s": 1800},
    "server": {"sys_interval_s": 5},
})
(data / "paper1.yaml").write_text("# paper-1 campaign config (generated by research/paper1/setup_vm.sh)\n" +
                                  yaml.safe_dump(conf, sort_keys=False))
print((data / "paper1.yaml").read_text())
EOF
mkdir -p "$DATA/paper1" "$DATA/kdd/inbox"
chown -R gatemoe:gatemoe "$DATA/paper1" "$DATA/kdd" "$DATA/paper1.yaml"

log "Helper: paper1"
cat > /usr/local/bin/paper1 <<EOF
#!/usr/bin/env bash
# paper-1 campaign helper:  paper1 status | log | phase-log <phase> | start | stop | restart | analyze | bundle
RUN=(sudo -u gatemoe env HOME=$HOME_DIR GATEMOE_CONFIG=$DATA/paper1.yaml PAPER1_DIR=$DATA/paper1 \\
     $VENV/bin/python $SRC/research/paper1/run.py)
case "\${1:-status}" in
  status)    "\${RUN[@]}" status ;;
  log)       tail -n 40 -f $DATA/paper1/logs/runner.log ;;
  phase-log) tail -n 80 -f $DATA/paper1/logs/\${2:?phase name, e.g. p4_e2e}.log ;;
  start|stop|restart) sudo systemctl "\$1" gatemoe-paper1 && sudo systemctl --no-pager status gatemoe-paper1 | head -5 ;;
  analyze)   "\${RUN[@]}" analyze ;;
  bundle)    "\${RUN[@]}" bundle && ls -lh $HOME_DIR/paper1_bundles ;;
  *) echo "usage: paper1 status | log | phase-log <phase> | start | stop | restart | analyze | bundle"; exit 1 ;;
esac
EOF
chmod 755 /usr/local/bin/paper1

log "systemd service gatemoe-paper1"
cat > /etc/systemd/system/gatemoe-paper1.service <<EOF
[Unit]
Description=GateMoE paper-1 measurement campaign ($DAYS days, resumable)
After=network-online.target
Wants=network-online.target

[Service]
User=gatemoe
WorkingDirectory=$SRC
Environment=HOME=$HOME_DIR
Environment=GATEMOE_CONFIG=$DATA/paper1.yaml
Environment=PAPER1_DIR=$DATA/paper1
Environment=PYTHONUNBUFFERED=1
ExecStart=$VENV/bin/python $SRC/research/paper1/run.py run --days $DAYS
Restart=on-failure
RestartSec=60
TimeoutStopSec=90
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable -q gatemoe-paper1

FREE=$(df -BG --output=avail "$DATA" | tail -1 | tr -dc 0-9)
if [ "$FREE" -lt 6 ]; then
  warn "only ${FREE} GB free: the campaign needs ~3 GB for results; the 3-bit router quant and new Kiwix archives
    are skipped below ~9 GB. Growing the disk to 50 GB costs about \$2/month - see docs/PAPER1_EXPERIMENT.md."
fi
if [ "${NO_START:-0}" = 1 ]; then
  echo "set up; start with: sudo systemctl start gatemoe-paper1"
else
  systemctl restart gatemoe-paper1
  sleep 5
  sudo -u gatemoe env HOME=$HOME_DIR GATEMOE_CONFIG=$DATA/paper1.yaml PAPER1_DIR=$DATA/paper1 \
    "$VENV/bin/python" "$SRC/research/paper1/run.py" status || true
fi
cat <<EOF

========================================================================
 Paper-1 campaign is running as the service gatemoe-paper1.
   paper1 status        progress, ETA, disk, last errors   (check once a day)
   paper1 log           follow the runner log (Ctrl+C to leave)
   paper1 bundle        at the end: analysis + results archive to send back
 It resumes by itself after a reboot. Results: $DATA/paper1
========================================================================
EOF
